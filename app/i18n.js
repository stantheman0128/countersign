/** @param {"en" | "zh"} lang */
export function makeT(lang) {
  const table = STRINGS[lang] ?? STRINGS.en;
  return (key, vars = {}) => {
    const template = table[key] ?? STRINGS.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? "{" + name + "}").toString());
  };
}
